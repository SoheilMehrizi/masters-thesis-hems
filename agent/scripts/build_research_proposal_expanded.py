def node(parent,name,value='1'):
    el=parent.find(qn('w:'+name))
    if el is None:
        el=OxmlElement('w:'+name);parent.append(el)
    el.set(qn('w:val'),value)
    return el

def run(p,text,size=11.2,bold=False,rtl=True):
    r=p.add_run(text)
    r.font.name=FONT if rtl else 'Arial'
    r.font.size=Pt(size);r.font.bold=bold;r.font.color.rgb=RGBColor(0,0,0)
    pr=r._element.get_or_add_rPr()
    for kind in ['ascii','hAnsi','cs','eastAsia']:
        pr.rFonts.set(qn('w:'+kind),FONT if rtl else 'Arial')
    node(pr,'rtl','1' if rtl else '0');node(pr,'szCs',str(round(size*2)))
    node(pr,'bCs','1' if bold else '0')
    lang=node(pr,'lang','fa-IR' if rtl else 'en-US');lang.set(qn('w:bidi'),'fa-IR')
    return r

def runs(p,text,size=11.2,bold=False):
    for t in re.split(r'([A-Za-z][A-Za-z0-9 /+−().–-]*[A-Za-z0-9)]|\[[0-9، ,–-]+\])',text):
        if t:run(p,t,size,bold,not bool(re.match(r'[A-Za-z\[]',t)))

def fmt(p,size=11.2,space=5,keep=False):
    pr=p._p.get_or_add_pPr();node(pr,'bidi');node(pr,'jc','start')
    f=p.paragraph_format
    f.space_after=Pt(space);f.line_spacing=Pt(size*1.48)
    f.keep_with_next=keep;f.widow_control=True

def para(text,size=11.2,bold=False,space=5,keep=False,style=None):
    p=doc.add_paragraph(style=style);fmt(p,size,space,keep);runs(p,text,size,bold)
    return p

def h(text,level=1):
    # Avoid ambiguous ordering of spaced Persian subsection numerals in Word.
    text=re.sub(r'^[۰-۹]+ [۰-۹]+ ','',text)
    p=para(text,13 if level==1 else 11.7,True,5,True,'Heading '+str(level))
    p.paragraph_format.space_before=Pt(8 if level==1 else 5)
    return p

def page(title):
    doc.add_page_break();h(title)

def figure(name,caption,alt,width=17.2):
    p=doc.add_paragraph();p.alignment=WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_after=Pt(5);p.paragraph_format.keep_with_next=True
    shape=p.add_run().add_picture(str(ASSETS/name),width=Cm(width))
    shape._inline.docPr.set('descr',alt)
    cp=para(caption,9.5,space=7);cp.paragraph_format.line_spacing=Pt(14)

def table(headers,rows,widths,size=10.2):
    t=doc.add_table(rows=0,cols=len(headers));t.alignment=WD_TABLE_ALIGNMENT.CENTER;t.autofit=False
    pr=t._tbl.tblPr;node(pr,'bidiVisual')
    borders=OxmlElement('w:tblBorders')
    for side in ['top','left','bottom','right','insideH','insideV']:
        e=OxmlElement('w:'+side)
        for k,v in [('val','single'),('sz','4'),('color','D9D9D9')]:e.set(qn('w:'+k),v)
        borders.append(e)
    pr.append(borders)
    margins=OxmlElement('w:tblCellMar')
    for side,v in [('top','85'),('bottom','85'),('left','95'),('right','95')]:
        e=OxmlElement('w:'+side);e.set(qn('w:w'),v);e.set(qn('w:type'),'dxa');margins.append(e)
    pr.append(margins)
    for col,w in zip(t.columns,widths):col.width=Cm(w)
    for i,rowdata in enumerate([headers]+rows):
        row=t.add_row();node(row._tr.get_or_add_trPr(),'cantSplit')
        if i==0:node(row._tr.get_or_add_trPr(),'tblHeader')
        for j,text in enumerate(rowdata):
            c=row.cells[j];c.width=Cm(widths[j]);c.vertical_alignment=WD_CELL_VERTICAL_ALIGNMENT.CENTER
            sh=OxmlElement('w:shd');sh.set(qn('w:fill'),'E8EEF2' if i==0 else ('F6F8FA' if i%2==0 else 'FFFFFF'));c._tc.get_or_add_tcPr().append(sh)
            p=c.paragraphs[0];fmt(p,size,1);runs(p,text,size,i==0)
    doc.add_paragraph().paragraph_format.space_after=Pt(1)
    return t

